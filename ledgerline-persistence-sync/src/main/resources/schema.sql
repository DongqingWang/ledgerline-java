CREATE TABLE IF NOT EXISTS journal_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transfer_dedup_id TEXT NOT NULL,
  account_id TEXT NOT NULL,
  direction TEXT NOT NULL CHECK (direction IN ('debit','credit')),
  amount_minor BIGINT NOT NULL CHECK (amount_minor > 0),
  currency TEXT NOT NULL,
  gl_account TEXT,
  cost_center TEXT,
  posted_at TIMESTAMP WITH TIME ZONE NOT NULL,
  raft_index BIGINT NOT NULL,
  UNIQUE(transfer_dedup_id,account_id,direction)
);
CREATE INDEX IF NOT EXISTS journal_account_index ON journal_entries(account_id,raft_index);
CREATE TABLE IF NOT EXISTS account_balances (
  account_id TEXT PRIMARY KEY,
  currency TEXT NOT NULL,
  balance_minor BIGINT NOT NULL DEFAULT 0,
  last_raft_index BIGINT NOT NULL DEFAULT 0,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sync_state (
  id INT PRIMARY KEY,
  last_raft_index BIGINT NOT NULL DEFAULT 0
);
INSERT INTO sync_state(id,last_raft_index) SELECT 1,0 WHERE NOT EXISTS (SELECT 1 FROM sync_state WHERE id=1);
